await page.keyboard.press('PageDown');
await page.waitForTimeout(300);
console.log('PageDown', await page.evaluate(() => ({ top: __el.scrollTop, panel: venezia.store.view.get().panel })));
await page.evaluate(() => { __el.focus(); });
await page.keyboard.press('Space');
await page.waitForTimeout(300);
console.log('Space on scroller', await page.evaluate(() => ({ top: __el.scrollTop, voice: document.querySelector('.deck').dataset.voice })));
await page.keyboard.up('Space');

