// Things a keyboard user meets on the main page: scrolling with arrows, focus surviving updates,
// focus after a card goes, skip links, leaves, sheet.
import path from 'node:path';
import { OUT, focusInfo, launch, line, tabWalk } from './audit-lib.mjs';
import { SAMPLE, clearInbox, raise } from './harness.mjs';

const { page, errors, close } = await launch({ wrap: true, query: 'demo=fleet&nosw=1&ambient=0&speed=0.001' });
await page.waitForTimeout(500);

console.log('== arrows in a scrollable focused region');
const shipId = await page.evaluate(() => {
  const { store } = venezia;
  const ship = Object.values(store.getLiveState().ships).find((s) => s.state !== 'scuttled' && s.state !== 'done') ?? Object.values(store.getLiveState().ships)[0];
  store.view.set({ selectedShip: ship.id, panel: 'chronicle' });
  return ship.id;
});
await page.waitForTimeout(300);
const scrollProbe = async (sel) => {
  const info = await page.evaluate((s) => {
    const el = document.querySelector(s);
    if (!el) return null;
    el.focus();
    return { tabindex: el.getAttribute('tabindex'), sh: el.scrollHeight, ch: el.clientHeight, top: el.scrollTop, active: document.activeElement === el, role: el.getAttribute('role') };
  }, sel);
  console.log(sel, info);
};
const scrollers = await page.evaluate(() => [...document.querySelectorAll('*')].filter((e) => e.scrollHeight > e.clientHeight + 2 && /auto|scroll/.test(getComputedStyle(e).overflowY) && e.offsetParent).map((e) => `${e.tagName}.${e.className} tabindex=${e.getAttribute('tabindex')} sh=${e.scrollHeight} ch=${e.clientHeight}`));
console.log(scrollers);
await page.evaluate(() => { const el = document.querySelector('.tab-body:not([hidden])') ?? document.querySelector('.tab-host'); window.__el = el; el.focus(); });
const before = await page.evaluate(() => ({ cls: __el.className, top: __el.scrollTop, panel: venezia.store.view.get().panel, tag: document.activeElement.className }));
await page.keyboard.press('ArrowDown');
await page.keyboard.press('ArrowDown');
await page.waitForTimeout(200);
const after = await page.evaluate(() => ({ top: __el.scrollTop, panel: venezia.store.view.get().panel, active: document.activeElement.className }));
console.log('ArrowDown on focused scroller', before, after);
await page.evaluate(() => venezia.store.view.set({ panel: 'chronicle' }));
await page.waitForTimeout(200);
await page.evaluate(() => { __el.focus(); });
await page.keyboard.press('ArrowUp');
await page.waitForTimeout(100);
console.log('ArrowUp', await page.evaluate(() => ({ top: __el.scrollTop, panel: venezia.store.view.get().panel })));
